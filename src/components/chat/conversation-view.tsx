'use client';

import React, { useEffect, useRef } from 'react';
import type { Conversation } from './types';
import { getModel } from './data';
import { AIMessage, TypingRow, UserMessage } from './messages';

export function ConversationView({
  conversation,
  pending,
  onRegenerate,
  onFeedback,
  onDeleteMessage,
}: {
  conversation: Conversation;
  pending: boolean;
  onRegenerate: () => void;
  onFeedback: (id: string, v: 'up' | 'down') => void;
  onDeleteMessage: (id: string) => void;
}) {
  const box = useRef<HTMLDivElement>(null);
  const count = conversation.messages.length;
  const model = getModel(conversation.modelId);

  useEffect(() => {
    box.current?.scrollTo({ top: box.current.scrollHeight, behavior: 'smooth' });
  }, [count, pending, conversation.id]);

  const last = conversation.messages[count - 1];

  return (
    <div ref={box} className="h-full overflow-y-auto">
      <div className="mx-auto max-w-3xl space-y-7 px-4 py-6 sm:px-6">
        {conversation.sample && (
          <p className="rounded-xl border border-white/[0.1] bg-white/[0.03] px-4 py-3 text-center text-[12.5px] leading-5 text-white/55">
            Sample conversation, written by hand to show the layout. It was not generated by any AI model.
          </p>
        )}

        {conversation.messages.map((m) =>
          m.role === 'user' ? (
            <UserMessage key={m.id} message={m} />
          ) : (
            <AIMessage
              key={m.id}
              message={m}
              model={getModel(m.modelId ?? conversation.modelId)}
              canRegenerate={m.id === last?.id && m.kind === 'notice' && !pending}
              onRegenerate={onRegenerate}
              onFeedback={(v) => onFeedback(m.id, v)}
              onDelete={() => onDeleteMessage(m.id)}
            />
          )
        )}

        {pending && <TypingRow model={model} />}
      </div>
    </div>
  );
}